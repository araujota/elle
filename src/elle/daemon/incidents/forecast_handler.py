def _check_plan_autonomy(capabilities: tuple[str, ...]) -> bool:
    """Check if ALL capabilities in the plan can run autonomously.

    Args:
        capabilities: Tuple of capability names from the plan.

    Returns:
        True if all capabilities can auto-run, False if any require confirmation.
    """
    if not capabilities:
        return False

    try:
        from elle.capabilities.autonomy import get_autonomy_engine
        from elle.capabilities.registry import get_registry

        engine = get_autonomy_engine()
        registry = get_registry()

        for cap_name in capabilities:
            capability = registry.get(cap_name)
            if capability is None:
                # Unknown capability - can't auto-run
                return False

            can_auto, _reason = engine.can_run_autonomously(cap_name, capability.spec.risk)
            if not can_auto:
                return False

        return True

    except ImportError:
        logger.debug("Autonomy engine not available")
        return False
    except Exception as e:
        logger.warning(f"Autonomy check failed: {e}")
        return False


async def _notify_forecast_warning(
    forecast: Forecast,
    incident_id: str,
    plan: RemediationPlan,
) -> None:
    """Send pre-execution notification with plan details.

    Args:
        forecast: The forecast that triggered.
        incident_id: The incident ID.
        plan: The generated remediation plan.
    """
    try:
        from elle.daemon.notifications.service import notify_forecast

        threshold = forecast.warning_threshold or 0.0

        notify_forecast(
            metric=forecast.metric,
            current_value=forecast.current_value,
            threshold=threshold,
            time_to_threshold_hours=forecast.time_to_warning_hours,
            incident_id=incident_id,
            plan_summary=plan.summary,
            cause_description=plan.cause_description,
            auto_remediated=False,
        )
    except Exception as e:
        logger.warning(f"Failed to send forecast warning notification: {e}")


async def _notify_forecast_remediated(
    forecast: Forecast,
    incident_id: str,
    outcome: str,
    plan_summary: str | None = None,
    cause_description: str | None = None,
) -> None:
    """Send post-execution notification with outcome.

    Args:
        forecast: The forecast that triggered.
        incident_id: The incident ID.
        outcome: The remediation outcome.
        plan_summary: Summary of the plan that was executed.
        cause_description: Description of the cause.
    """
    try:
        from elle.daemon.notifications.service import notify_forecast

        threshold = forecast.critical_threshold or forecast.warning_threshold or 0.0

        notify_forecast(
            metric=forecast.metric,
            current_value=forecast.current_value,
            threshold=threshold,
            time_to_threshold_hours=forecast.time_to_warning_hours,
            incident_id=incident_id,
            plan_summary=plan_summary,
            cause_description=cause_description,
            auto_remediated=True,
            outcome=outcome,
        )
    except Exception as e:
        logger.warning(f"Failed to send forecast remediated notification: {e}")


async def execute_prepared_plan(incident_id: str) -> ForecastIncidentResult:
    """Execute a previously prepared plan (triggered by user action).

    Loads the prepared plan from the incident store and runs the
    Agent Loop in execution mode.

    Args:
        incident_id: The incident ID with a prepared plan.

    Returns:
        ForecastIncidentResult with execution outcome.
    """
    try:
        from elle.daemon.incidents.store import get_prepared_plan

        plan_data = get_prepared_plan(incident_id)
        if not plan_data:
            return ForecastIncidentResult(
                incident_id=incident_id,
                urgency="prepare",
                executed=False,
                success=False,
                error="No prepared plan found for this incident",
            )

        plan = RemediationPlan(**plan_data)

        # Build execution query from the plan
        from elle.cli.agentic.loop import AgenticLoop

        steps_text = "\n".join(f"- {step}" for step in plan.steps)
        query = (
            f"Execute the following remediation plan for metric {plan.metric} "
            f"(current: {plan.current_value:.1f}, threshold: {plan.threshold}):\n"
            f"{steps_text}\n"
            f"Execute the required capabilities to address this issue."
        )

        loop = AgenticLoop(
            prefetch_context=True,
            enable_audit=True,
            enable_verification=True,
        )

        result = await loop.run(query)

        # Update incident outcome
        await _update_incident_outcome(
            incident_id,
            success=result.success,
            response=result.response,
        )

        # Send post-execution notification
        outcome = "improved" if result.success else "no_change"
        try:
            from elle.daemon.notifications.service import notify_forecast

            notify_forecast(
                metric=plan.metric,
                current_value=plan.current_value,
                threshold=plan.threshold,
                time_to_threshold_hours=None,
                incident_id=incident_id,
                plan_summary=plan.summary,
                cause_description=plan.cause_description,
                auto_remediated=True,
                outcome=outcome,
            )
        except Exception as e:
            logger.warning(f"Failed to send post-execution notification: {e}")

        return ForecastIncidentResult(
            incident_id=incident_id,
            urgency="prepare",
            plan=plan,
            executed=True,
            success=result.success,
            error=result.error,
        )

    except Exception as e:
        logger.exception(f"Failed to execute prepared plan: {e}")
        return ForecastIncidentResult(
            incident_id=incident_id,
            urgency="prepare",
            executed=False,
            success=False,
            error=str(e),
        )


# =============================================================================
# Response Parsing Helpers
# =============================================================================


def _parse_plan_steps(response: str) -> list[str]:
    """Parse plan steps from the agent's response.

    Looks for numbered lists or bullet points.

    Args:
        response: The agent's response text.

    Returns:
        List of plan steps.
    """
    import re

    steps = []

    # Look for numbered steps
    numbered = re.findall(r"^\d+\.\s+(.+)$", response, re.MULTILINE)
    if numbered:
        steps.extend(numbered)

    # Look for bullet points
    bullets = re.findall(r"^[-*]\s+(.+)$", response, re.MULTILINE)
    if bullets and not numbered:
        steps.extend(bullets)

    return steps if steps else ["See response for details"]


def _extract_capabilities(response: str) -> list[str]:
    """Extract capability names mentioned in the response.

    Args:
        response: The agent's response text.

    Returns:
        List of capability names.
    """
    import re

    # Look for capability patterns like "service.restart", "file.write", etc.
    pattern = r"\b([a-z]+\.[a-z_]+)\b"
    capabilities = set(re.findall(pattern, response.lower()))

    # Filter to known capability prefixes
    known_prefixes = {"service", "file", "config", "docker", "package", "network"}
    return [c for c in capabilities if c.split(".")[0] in known_prefixes]


def _extract_summary(response: str) -> str:
    """Extract a summary from the agent's response.

    Takes the first paragraph or first 200 characters.

    Args:
        response: The agent's response text.

    Returns:
        Summary string.
    """
    # Take first paragraph
    paragraphs = response.split("\n\n")
    if paragraphs:
        summary = paragraphs[0].strip()
        if len(summary) > 200:
            summary = summary[:197] + "..."
        return summary
    return response[:200] if len(response) > 200 else response


def _extract_cause_description(response: str) -> str | None:
    """Extract cause/reason from Agent Loop response.

    Looks for common patterns like "Cause:", "Root cause:", "Reason:",
    "This is likely due to", etc.

    Args:
        response: The agent's response text.

    Returns:
        Cause description, or None if not found.
    """
    import re

    # Look for explicit cause labels
    patterns = [
        r"(?:root\s+)?cause[:\s]+(.+?)(?:\n|$)",
        r"reason[:\s]+(.+?)(?:\n|$)",
        r"(?:this\s+is\s+)?(?:likely\s+)?(?:due\s+to|caused\s+by)[:\s]+(.+?)(?:\n|$)",
        r"problem[:\s]+(.+?)(?:\n|$)",
    ]

    for pattern in patterns:
        match = re.search(pattern, response, re.IGNORECASE)
        if match:
            cause = match.group(1).strip()
            if len(cause) > 120:
                cause = cause[:117] + "..."
            if len(cause) > 10:  # Skip very short matches
                return cause

    return None
