"""Forecast-triggered incident handler.

Creates incidents and runs the Agent Loop when forecast triggers fire.
This is the bridge between the reactive engine (forecast triggers) and
the Agent Loop (remediation planning/execution).

When a forecast trigger fires:
1. Create incident report with forecast evidence
2. Run Agent Loop to generate remediation plan
3. If act_now: Execute plan immediately
4. If prepare: Store plan, notify user

All functionality flows through The Spine:
DAEMON (trends) -> SIGNALS (reactive/engine) -> INCIDENT REPORT (this module)
-> AGENT LOOP -> CAPABILITIES -> OUTCOME -> INCIDENT MEMORY
"""

from __future__ import annotations

import logging
from datetime import datetime, timezone
from typing import TYPE_CHECKING, Any, Literal

from pydantic import BaseModel, ConfigDict, Field

if TYPE_CHECKING:
    from elle.daemon.telemetry.trends import Forecast

logger = logging.getLogger(__name__)


# =============================================================================
# Models
# =============================================================================


class RemediationPlan(BaseModel):
    """A remediation plan generated by the Agent Loop.

    Contains the planned approach for addressing a forecast alert,
    which can be stored and executed later.
    """

    model_config = ConfigDict(frozen=True)

    # Identity
    plan_id: str = Field(description="Unique plan identifier")
    incident_id: str = Field(description="Linked incident ID")

    # What triggered this plan
    metric: str = Field(description="Metric that triggered the plan")
    current_value: float = Field(description="Value at time of planning")
    threshold: float = Field(description="Threshold being approached")
    urgency: Literal["prepare", "act_now"] = Field(description="Urgency level")

    # The plan itself
    summary: str = Field(description="Brief summary of the plan")
    cause_description: str | None = Field(
        default=None,
        description="Description of the probable cause",
    )
    steps: tuple[str, ...] = Field(
        default_factory=tuple,
        description="Ordered list of remediation steps",
    )
    capabilities_to_execute: tuple[str, ...] = Field(
        default_factory=tuple,
        description="Capability names that will be executed",
    )

    # Metadata
    generated_by: str = Field(
        default="agent_loop",
        description="What generated this plan",
    )
    generated_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    confidence: float = Field(
        default=0.5,
        ge=0.0,
        le=1.0,
        description="Confidence in the plan's effectiveness",
    )

    # Execution state
    executed: bool = Field(default=False, description="Whether plan was executed")
    executed_at: datetime | None = Field(default=None)
    execution_result: str | None = Field(default=None)


class ForecastIncidentResult(BaseModel):
    """Result of handling a forecast trigger."""

    model_config = ConfigDict(frozen=True)

    incident_id: str = Field(description="Created/updated incident ID")
    urgency: Literal["prepare", "act_now"] = Field(description="Urgency level")
    plan: RemediationPlan | None = Field(
        default=None,
        description="Generated plan (for 'prepare' urgency)",
    )
    executed: bool = Field(
        default=False,
        description="Whether remediation was executed",
    )
    success: bool = Field(description="Whether handling succeeded")
    error: str | None = Field(default=None, description="Error if failed")


