# Forecast Handler
# =============================================================================


async def handle_forecast_trigger(
    forecast: Forecast,
    urgency: Literal["prepare", "act_now"],
) -> ForecastIncidentResult:
    """Handle a forecast trigger through The Spine.

    This is the main entry point when a forecast crosses urgency thresholds.

    Flow:
    1. Create incident from forecast evidence
    2. Run Agent Loop to generate/execute remediation
    3. Record outcome to incident memory

    Args:
        forecast: The Forecast that triggered.
        urgency: The urgency level ('prepare' or 'act_now').

    Returns:
        ForecastIncidentResult with incident ID and outcome.
    """
    try:
        # 1. Create incident from forecast
        incident_data = create_forecast_incident(
            metric=forecast.metric,
            current_value=forecast.current_value,
            threshold=(forecast.critical_threshold if urgency == "act_now" else forecast.warning_threshold) or 0.0,
            time_to_threshold=(
                forecast.time_to_critical_hours if urgency == "act_now" else forecast.time_to_warning_hours
            ),
            rate_of_change=forecast.rate_of_change,
            urgency=urgency,
            confidence=forecast.confidence,
        )

        incident_id = incident_data["id"]

        # Store the incident
        try:
            from elle.daemon.incidents.store import create_incident_draft, update_incident

            report = create_incident_draft(
                title=incident_data.get("title", f"Forecast: {forecast.metric}"),
                domain=incident_data.get("domain", "other"),
                severity=incident_data.get("severity", "warning"),
                trigger_source=incident_data.get("trigger_source", "forecast"),
            )
            incident_id = report.incident_id
            incident_data["id"] = incident_id
            update_incident(
                incident_id,
                summary=incident_data.get("summary"),
                outcome=incident_data.get("outcome"),
                metrics=incident_data.get("metrics_json"),
                status=incident_data.get("status"),
            )
        except ImportError:
            logger.warning("Incident store not available, continuing without persistence")
        except Exception as e:
            logger.warning(f"Failed to persist incident: {e}")

        # 2. Run Agent Loop
        if urgency == "prepare":
            # Generate remediation plan
            plan = await _generate_remediation_plan(forecast, incident_id)

            # Store plan in incident
            await _update_incident_with_plan(incident_id, plan)

            # Check if all plan capabilities can auto-run
            can_auto = _check_plan_autonomy(plan.capabilities_to_execute)

            if can_auto and plan.capabilities_to_execute:
                # Auto-execute and notify AFTER
                success, error = await _execute_remediation(forecast, incident_id)
                outcome = "improved" if success else "no_change"

                await _notify_forecast_remediated(
                    forecast,
                    incident_id,
                    outcome,
                    plan_summary=plan.summary,
                    cause_description=plan.cause_description,
                )

                return ForecastIncidentResult(
                    incident_id=incident_id,
                    urgency=urgency,
                    plan=plan,
                    executed=True,
                    success=success,
                    error=error,
                )
            else:
                # Notify user with plan + "Execute Now" action
                await _notify_forecast_warning(
                    forecast,
                    incident_id,
                    plan,
                )

                return ForecastIncidentResult(
                    incident_id=incident_id,
                    urgency=urgency,
                    plan=plan,
                    executed=False,
                    success=True,
                )

        elif urgency == "act_now":
            # Execute remediation immediately
            success, error = await _execute_remediation(forecast, incident_id)

            # Notify after execution
            outcome = "improved" if success else "no_change"
            await _notify_forecast_remediated(
                forecast,
                incident_id,
                outcome,
            )

            return ForecastIncidentResult(
                incident_id=incident_id,
                urgency=urgency,
                plan=None,
                executed=True,
                success=success,
                error=error,
            )

        # Should not reach here
        return ForecastIncidentResult(
            incident_id=incident_id,
            urgency=urgency,
            executed=False,
            success=False,
            error=f"Unknown urgency level: {urgency}",
        )

    except Exception as e:
        logger.exception(f"Failed to handle forecast trigger: {e}")
        return ForecastIncidentResult(
            incident_id="",
            urgency=urgency,
            executed=False,
            success=False,
            error=str(e),
        )


async def _generate_remediation_plan(
    forecast: Forecast,
    incident_id: str,
) -> RemediationPlan:
    """Generate a remediation plan using the Agent Loop.

    This runs the Agent Loop in planning mode - it generates a plan
    but doesn't execute any capabilities.

    Args:
        forecast: The forecast that triggered.
        incident_id: The incident ID for context.

    Returns:
        RemediationPlan with the generated steps.
    """
    import uuid

    try:
        from elle.cli.agentic.loop import AgenticLoop

        # Build the planning query
        query = (
            f"Metric {forecast.metric} is currently at {forecast.current_value:.1f} "
            f"and is projected to breach the warning threshold of {forecast.warning_threshold} "
            f"in {forecast.time_to_warning_hours:.1f} hours. "
            f"Generate a remediation plan to prevent this threshold breach. "
            f"Do NOT execute any capabilities - only plan the remediation steps."
        )

        loop = AgenticLoop(
            prefetch_context=True,
            enable_audit=True,
            enable_verification=False,  # Planning only
        )

        # Run in planning mode
        result = await loop.run(query)

        # Parse the response into a plan
        # The response should contain the plan steps
        steps = _parse_plan_steps(result.response)

        # Extract mentioned capabilities
        capabilities = _extract_capabilities(result.response)

        # Extract cause description from response
        cause_description = _extract_cause_description(result.response)

        return RemediationPlan(
            plan_id=uuid.uuid4().hex,
            incident_id=incident_id,
            metric=forecast.metric,
            current_value=forecast.current_value,
            threshold=forecast.warning_threshold or 0.0,
            urgency="prepare",
            summary=_extract_summary(result.response),
            cause_description=cause_description,
            steps=tuple(steps),
            capabilities_to_execute=tuple(capabilities),
            confidence=forecast.confidence,
            generated_at=datetime.now(timezone.utc),
        )

    except Exception as e:
        logger.exception(f"Failed to generate remediation plan: {e}")
        # Return a minimal plan with the error
        return RemediationPlan(
            plan_id=uuid.uuid4().hex,
            incident_id=incident_id,
            metric=forecast.metric,
            current_value=forecast.current_value,
            threshold=forecast.warning_threshold or 0.0,
            urgency="prepare",
            summary=f"Failed to generate plan: {e}",
            steps=(),
            capabilities_to_execute=(),
            confidence=0.0,
            generated_at=datetime.now(timezone.utc),
        )


async def _execute_remediation(
    forecast: Forecast,
    incident_id: str,
) -> tuple[bool, str | None]:
    """Execute remediation using the Agent Loop.

    This runs the Agent Loop in execution mode - it can execute
    capabilities to address the issue.

    Args:
        forecast: The forecast that triggered.
        incident_id: The incident ID for context.

    Returns:
        Tuple of (success, error_message).
    """
    try:
        from elle.cli.agentic.loop import AgenticLoop

        # Build the execution query
        query = (
            f"URGENT: Metric {forecast.metric} is at {forecast.current_value:.1f}, "
            f"projected to breach critical threshold of {forecast.critical_threshold} "
            f"in {forecast.time_to_critical_hours:.1f} hours. "
            f"Execute remediation immediately to prevent system impact."
        )

        loop = AgenticLoop(
            prefetch_context=True,
            enable_audit=True,
            enable_verification=True,
        )

        result = await loop.run(query)

        # Update incident with outcome
        await _update_incident_outcome(
            incident_id,
            success=result.success,
            response=result.response,
        )

        return result.success, result.error

    except Exception as e:
        logger.exception(f"Failed to execute remediation: {e}")
        return False, str(e)


async def _update_incident_with_plan(
    incident_id: str,
    plan: RemediationPlan,
) -> None:
    """Update an incident with the prepared plan.

    Args:
        incident_id: The incident ID.
        plan: The remediation plan.
    """

    try:
        from elle.daemon.incidents.store import update_incident

        update_incident(
            incident_id,
            metrics={"prepared_plan": plan.model_dump(mode="json")},
        )
    except ImportError:
        logger.debug("Incident store not available")
    except Exception as e:
        logger.warning(f"Failed to update incident with plan: {e}")


async def _update_incident_outcome(
    incident_id: str,
    success: bool,
    response: str,
) -> None:
    """Update an incident with the execution outcome.

    Args:
        incident_id: The incident ID.
        success: Whether execution succeeded.
        response: The agent's response.
    """
    try:
        from elle.daemon.incidents.store import update_incident

        outcome = "improved" if success else "no_change"
        status = "mitigated" if success else "open"

        update_incident(
            incident_id,
            outcome=outcome,
            status=status,
            metrics={"plan_executed_at": datetime.now(timezone.utc).isoformat()},
        )
    except ImportError:
        logger.debug("Incident store not available")
    except Exception as e:
        logger.warning(f"Failed to update incident outcome: {e}")


