def create_forecast_incident(
    metric: str,
    current_value: float,
    threshold: float,
    time_to_threshold: float | None,
    rate_of_change: float,
    urgency: Literal["prepare", "act_now"],
    confidence: float = 0.5,
) -> dict[str, Any]:
    """Create an incident dict for a forecast trigger.

    Args:
        metric: The metric that triggered (e.g., "disk./.used_pct").
        current_value: Current metric value.
        threshold: Threshold being approached.
        time_to_threshold: Hours until threshold is crossed.
        rate_of_change: Rate of change per hour.
        urgency: The urgency level.
        confidence: Forecast confidence.

    Returns:
        Dict suitable for incident creation.
    """
    import uuid

    incident_id = f"FORECAST-{uuid.uuid4().hex[:8].upper()}"

    # Determine severity based on urgency
    severity = "warning" if urgency == "prepare" else "critical"

    # Extract domain from metric
    domain = metric.split(".")[0] if "." in metric else "system"

    # Build title
    if time_to_threshold is not None:
        time_str = f"{time_to_threshold:.1f}h"
    else:
        time_str = "imminent"

    title = (
        f"Forecast: {metric} projected to reach {threshold} in {time_str}"
        if urgency == "prepare"
        else f"URGENT: {metric} at {current_value:.1f}, {threshold} threshold imminent"
    )

    return {
        "id": incident_id,
        "created_at": datetime.now(timezone.utc).isoformat(),
        "updated_at": datetime.now(timezone.utc).isoformat(),
        "domain": domain,
        "severity": severity,
        "status": "open",
        "title": title,
        "summary": (
            f"Metric {metric} is currently at {current_value:.1f} and is projected "
            f"to cross the {'warning' if urgency == 'prepare' else 'critical'} "
            f"threshold of {threshold} at a rate of {rate_of_change:.2f}/hour. "
            f"Forecast confidence: {confidence:.0%}."
        ),
        "trigger_source": "forecast",
        "forecast_metric": metric,
        "forecast_urgency": urgency,
        "metrics_json": {
            "metric": metric,
            "current_value": current_value,
            "threshold": threshold,
            "time_to_threshold_hours": time_to_threshold,
            "rate_of_change": rate_of_change,
            "confidence": confidence,
        },
    }


